export function buildDeterministicEvaluation(
  stepNumber: number,
  passed: boolean,
  score: number,
  summary: string,
  feedback: string,
  strengths: string[] = [],
  improvements: string[] = [],
  flags: string[] = [],
  isAiGenerated: boolean = false,
  aiConfidenceScore: number = 0
): AIEvaluationResult {
  const normScore = clampScore(score);
  const meetsThreshold = normScore >= SIMULATION_PASSING_THRESHOLD;
  const finalPassed = passed && meetsThreshold && !isAiGenerated;
  return {
    step_number: stepNumber,
    passed: finalPassed,
    step_score: normScore,
    competency_scores: {
      community_investigation: stepNumber === 1 ? normScore : 82,
      evidence_evaluation: stepNumber === 3 ? normScore : 80,
      stakeholder_analysis: stepNumber === 4 ? normScore : 85,
      intervention_planning: stepNumber === 5 ? normScore : 80,
      adaptive_decision_making: stepNumber === 6 ? normScore : 84,
      impact_assessment: stepNumber === 7 ? normScore : 82,
    },
    overall_civic_score: normScore,
    flags,
    is_ai_generated: isAiGenerated,
    ai_confidence_score: aiConfidenceScore,
    evaluation_summary: summary,
    strengths: strengths.length > 0 ? strengths : [passed ? "Demonstrates relevant civic reasoning." : "Attempted initial response."],
    areas_for_improvement: improvements.length > 0 ? improvements : (passed ? [] : ["Provide more concrete evidence and details."]),
    actionable_feedback: feedback,
  };
}

export function sanitizeEvaluationResult(evaluation: AIEvaluationResult): AIEvaluationResult {
  return {
    ...evaluation,
    evaluation_summary: sanitizeEducationalText(evaluation.evaluation_summary),
    actionable_feedback: sanitizeEducationalText(evaluation.actionable_feedback),
    strengths: Array.isArray(evaluation.strengths)
      ? evaluation.strengths.map(sanitizeEducationalText)
      : [],
    areas_for_improvement: Array.isArray(evaluation.areas_for_improvement)
      ? evaluation.areas_for_improvement.map(sanitizeEducationalText)
      : [],
  };
}

function formatEvaluationResponse(evaluation: AIEvaluationResult) {
  const sanitized = sanitizeEvaluationResult(evaluation);
  const score = sanitized.step_score ?? 0;
  const isPassing = Boolean(sanitized.passed) && score >= SIMULATION_PASSING_THRESHOLD && !sanitized.is_ai_generated;

  let actionableFeedback = sanitized.actionable_feedback;
  if (!isPassing && score < SIMULATION_PASSING_THRESHOLD && !actionableFeedback.includes("70%")) {
    actionableFeedback = `${actionableFeedback} Note: A minimum score of ${SIMULATION_PASSING_THRESHOLD}% is required to continue to the next mission step (Current Score: ${score}%).`;
  }

  return {
    passed: isPassing,
    feedback: actionableFeedback,
    evaluation: {
      ...sanitized,
      passed: isPassing,
      actionable_feedback: actionableFeedback,
    },
  };
}

function quoteUntrustedText(value: unknown): string {
  return JSON.stringify(String(value ?? ""));
}

interface AIClientConfig {
  client: GoogleGenAI;
  model: string;
  provider: "vertex" | "gemini-studio";
}

function getAIClient(): AIClientConfig | null {
  const gcpProject = process.env.GCP_PROJECT_ID || process.env.GOOGLE_CLOUD_PROJECT;
  if (gcpProject) {
    const location = process.env.GCP_LOCATION || process.env.GOOGLE_CLOUD_LOCATION || "global";
    const model = process.env.GCP_MODEL || "gemini-3.8-flash";

    let googleAuthOptions: Record<string, unknown> | undefined = undefined;

    if (process.env.GCP_CLIENT_EMAIL && process.env.GCP_PRIVATE_KEY) {
      googleAuthOptions = {
        credentials: {
          client_email: process.env.GCP_CLIENT_EMAIL,
          private_key: process.env.GCP_PRIVATE_KEY.replace(/\\n/g, "\n"),
        },
      };
    } else if (process.env.GCP_SERVICE_ACCOUNT_KEY) {
      try {
        googleAuthOptions = {
          credentials: JSON.parse(process.env.GCP_SERVICE_ACCOUNT_KEY),
        };
      } catch (e) {
        console.error("[CiviConnect AI] Failed to parse GCP_SERVICE_ACCOUNT_KEY JSON:", e);
      }
    } else if (process.env.GOOGLE_APPLICATION_CREDENTIALS) {
      const rawPath = process.env.GOOGLE_APPLICATION_CREDENTIALS;
      const credsPath = path.isAbsolute(rawPath) ? rawPath : path.resolve(process.cwd(), rawPath);
      if (fs.existsSync(credsPath)) {
        googleAuthOptions = {
          keyFilename: credsPath,
        };
      } else {
        console.warn(`[CiviConnect AI] GOOGLE_APPLICATION_CREDENTIALS file not found at ${credsPath}.`);
      }
    }

    try {
      const client = new GoogleGenAI({
        vertexai: true,
        project: gcpProject,
        location,
        ...(googleAuthOptions ? { googleAuthOptions } : {}),
      });
      return { client, model, provider: "vertex" };
    } catch (err) {
      console.error("[CiviConnect AI] Vertex AI initialization failed:", err);
    }
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (apiKey) {
    try {
      const client = new GoogleGenAI({ apiKey });
      const model = process.env.GEMINI_MODEL || "gemini-3.7-flash";
      return { client, model, provider: "gemini-studio" };
    } catch (err) {
      console.error("[CiviConnect AI] Gemini Studio initialization failed:", err);
    }
  }

  return null;
}

async function callGeminiVerification(prompt: string, fallback: AIEvaluationResult): Promise<AIEvaluationResult> {
  const config = getAIClient();
  if (!config) {
    return fallback;
  }

  try {
    const fullPrompt = `${MASTER_SYSTEM_PROMPT}\n\n### EVALUATION TASK\n${prompt}`;
    let text = "";

    try {
      const res = await config.client.models.generateContent({
        model: config.model,
        contents: fullPrompt,
        config: {
          responseMimeType: "application/json",
          temperature: 0.2,
        },
      });
      text = res.text || "";
    } catch (primaryErr) {
      if (config.provider === "vertex" && process.env.GEMINI_API_KEY) {
        console.warn("[CiviConnect AI] Vertex AI request failed. Attempting fallback to Gemini Studio API Key:", primaryErr);
        try {
          const studioClient = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
          const res = await studioClient.models.generateContent({
            model: process.env.GEMINI_MODEL || "gemini-3.7-flash",
            contents: fullPrompt,
            config: {
              responseMimeType: "application/json",
              temperature: 0.2,
            },
          });
          text = res.text || "";
        } catch (fallbackErr) {
          console.error("[CiviConnect AI] Gemini Studio fallback also failed:", fallbackErr);
          return fallback;
        }
      } else {
        throw primaryErr;
      }
    }

    const match = text.match(/\{[\s\S]*\}/);
    if (!match) return fallback;

    const parsed = JSON.parse(match[0]);

    // Combine deterministic screening and Gemini's AI assessment:
    // If either the deterministic multi-signal screen found AI content OR Gemini detected AI-generated prose,
    // enforce the AI flag.
    const isAi = Boolean(fallback.is_ai_generated || parsed.is_ai_generated);
    const aiControlFlags = new Set([
      "AI_GENERATED_CONTENT",
      "AI_REVIEW_REQUIRED",
      "AI_REVIEW_RECOMMENDED",
    ]);
    const flags = Array.from(new Set<string>([
      ...fallback.flags,
      ...(Array.isArray(parsed.flags)
        ? parsed.flags.filter((flag: unknown): flag is string =>
            typeof flag === "string" && !aiControlFlags.has(flag)
          )
        : []),
      ...(isAi ? ["AI_GENERATED_CONTENT"] : []),
    ]));

    const parsedPassed = typeof parsed.passed === "boolean"
      ? parsed.passed
      : fallback.passed;
    const scoreOrFallback = (value: unknown, fallbackScore: number): number => {
      if (value === null || value === undefined || value === "") return fallbackScore;
      const numericValue = Number(value);
      return Number.isFinite(numericValue) ? clampScore(numericValue) : fallbackScore;
    };
    const parsedStepScore = scoreOrFallback(parsed.step_score, fallback.step_score);
    const parsedOverallScore = scoreOrFallback(parsed.overall_civic_score, fallback.overall_civic_score);

    const stepScore = isAi ? 35 : parsedStepScore;
    const meetsThreshold = stepScore >= SIMULATION_PASSING_THRESHOLD;
    const isPassed = !isAi && meetsThreshold && parsedPassed;

    return {
      step_number: Number(parsed.step_number) || fallback.step_number,
      passed: isPassed,
      step_score: stepScore,
      competency_scores: {
        community_investigation: scoreOrFallback(parsed.competency_scores?.community_investigation, fallback.competency_scores.community_investigation),
        evidence_evaluation: scoreOrFallback(parsed.competency_scores?.evidence_evaluation, fallback.competency_scores.evidence_evaluation),
        stakeholder_analysis: scoreOrFallback(parsed.competency_scores?.stakeholder_analysis, fallback.competency_scores.stakeholder_analysis),
        intervention_planning: scoreOrFallback(parsed.competency_scores?.intervention_planning, fallback.competency_scores.intervention_planning),
        adaptive_decision_making: scoreOrFallback(parsed.competency_scores?.adaptive_decision_making, fallback.competency_scores.adaptive_decision_making),
        impact_assessment: scoreOrFallback(parsed.competency_scores?.impact_assessment, fallback.competency_scores.impact_assessment),
      },
      overall_civic_score: isAi ? 35 : parsedOverallScore,
      flags,
      is_ai_generated: isAi,
      ai_confidence_score: isAi ? 95 : fallback.ai_confidence_score,
      evaluation_summary: isAi
        ? "AI-generated content detected. Grade 12 civic problem solving requires authentic student voice."
        : (parsed.evaluation_summary || fallback.evaluation_summary),
      strengths: isAi ? [] : (Array.isArray(parsed.strengths) ? parsed.strengths : fallback.strengths),
      areas_for_improvement: isAi
        ? ["Use authentic student voice and reference real community evidence from the scenario."]
        : (Array.isArray(parsed.areas_for_improvement) ? parsed.areas_for_improvement : fallback.areas_for_improvement),
      actionable_feedback: isAi
        ? "AI-generated content detected. Grade 12 civic engagement simulations require authentic student voice and local community evidence. Please discard AI-generated generalizations and rewrite your response in your own authentic words."
        : (parsed.actionable_feedback || fallback.actionable_feedback),
    };

  } catch (err) {
    console.error("[Civi-Tech AI Evaluator] Error:", err);
    return fallback;
  }
}

/**
 * Unified Pipeline: Runs Structural, AI-check, Anti-Fluff, and LLM verification.
 */
async function runStepPipeline({
  stepNumber,
  textToScan,
  structuralError,
  fluffCheckContext,
  fallbackScore,
  fallbackSummary,
  fallbackFeedback,
  fallbackFlags,
  strengths = [],
  improvements = [],
  authorshipOptions,
  prompt,
}: {
  stepNumber: number;
  textToScan?: string;
  structuralError?: { summary: string; feedback: string; flags: string[] } | null;
  fluffCheckContext?: string;
  fallbackScore: number;
  fallbackSummary: string;
  fallbackFeedback: string;
  fallbackFlags?: string[];
  strengths?: string[];
  improvements?: string[];
  authorshipOptions?: AIAuthorshipScreeningOptions;
  prompt: string;
}): Promise<{ passed: boolean; feedback: string; evaluation: AIEvaluationResult }> {
  const text = textToScan || "";
  const aiCheck = text
    ? detectAIGeneratedText(text, authorshipOptions)
    : null;
  const aiFlags = aiCheck?.isAi
    ? ["AI_GENERATED_CONTENT", "AI_REVIEW_REQUIRED"]
    : aiCheck?.needsReview
    ? ["AI_REVIEW_RECOMMENDED"]
    : [];

  // Pillar 1: Structural Check
  if (structuralError) {
    const combinedFlags = [...new Set([...structuralError.flags, ...aiFlags])];
    const authorshipNote = aiCheck?.isAi
      ? " A high-risk AI-authorship signal was also detected and requires manual review."
      : aiCheck?.needsReview
      ? " A separate authorship review is also recommended."
      : "";
    const evalRes = buildDeterministicEvaluation(
      stepNumber,
      false,
      35,
      structuralError.summary,
      `${structuralError.feedback}${authorshipNote}`,
      [],
      ["Complete all required fields."],
      combinedFlags,
      Boolean(aiCheck?.isAi),
      aiCheck?.confidence || 0
    );
    return formatEvaluationResponse(evalRes);
  }

  // AI Content Detection Gate (Multi-Tier)
  if (text) {
    // Pillar 2: Anti-Fluff Gate
    const fluffCheck = detectGenericFluff(text);
    if (fluffCheck.isFluff) {
      const evalRes = buildDeterministicEvaluation(
        stepNumber,
        false,
        45,
        "Justification relies on generic assertions rather than scenario evidence.",
        fluffCheckContext || "Your response is too generic. Civi-Tech requires evidence-based reasoning: reference specific metrics, local conditions, or affected populations mentioned in the scenario.",
        ["Addressed the topic."],
        ["Incorporate concrete facts or metrics from the scenario."],
        [...new Set(["GENERIC_FLUFF", ...aiFlags])],
        Boolean(aiCheck?.isAi),
        aiCheck?.confidence || 0
      );
      return formatEvaluationResponse(evalRes);
    }
  }

  // Pillar 3 & 4: LLM Verification with Deterministic Fallback
  const isFallbackPassing = !aiCheck?.isAi && fallbackScore >= SIMULATION_PASSING_THRESHOLD;
  const combinedFallbackFlags = [...new Set([...(fallbackFlags || []), ...aiFlags])];

  const fallback = buildDeterministicEvaluation(
    stepNumber,
    isFallbackPassing,
    aiCheck?.isAi ? 35 : fallbackScore,
    aiCheck?.isAi ? "High-risk AI-authorship signals detected." : fallbackSummary,
    aiCheck?.isAi
      ? aiCheck.reason || "High-risk authorship signals require manual review."
      : fallbackFeedback,
    strengths,
    improvements,
    combinedFallbackFlags,
    Boolean(aiCheck?.isAi),
    aiCheck?.confidence || 0
  );

  const evaluation = await callGeminiVerification(prompt, fallback);

  // Policy Hard Gate: ensure model cannot pass submissions with mismatch or structural flags
  const mismatchFlags = [
    "SELECTION_JUSTIFICATION_MISMATCH",
    "NOTES_STAKEHOLDER_MISMATCH",
    "PLAN_SCENARIO_MISMATCH",
    "IMPACT_SCENARIO_MISMATCH",
    "REFLECTION_SCENARIO_MISMATCH",
    "CONTEXT_RELEVANCE_MISMATCH",
    "DUPLICATE_FIELD_CONTENT",
    "INCORRECT_PRIORITY_ISSUE",
    "GENERIC_FLUFF",
  ];
  const hasMismatch = (evaluation.flags || []).some((f) => mismatchFlags.includes(f));
  if (hasMismatch) {
    evaluation.passed = false;
    evaluation.step_score = Math.min(evaluation.step_score, 55);
  }

  return formatEvaluationResponse(evaluation);
}

